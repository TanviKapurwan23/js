// 🌟 Non-Primitive (Reference) Data Types
let objectType = { name: "Alice", age: 25 }; // Object
let arrayType = [1, 2, 3, 4, 5]; // Array (a type of object)
let functionType = function() { return "I am a function"; }; // Function
let dateType = new Date(); // Date Object
let mapType = new Map([[1, "one"], [2, "two"]]); // Map
let setType = new Set([1, 2, 3, 3]); // Set

console.log("🚀 Non-Primitive (Reference) Data Types:");
console.log("Object:", objectType);
console.log("Array:", arrayType);
console.log("Function:", functionType());
console.log("Date:", dateType);
console.log("Map:", mapType);
console.log("Set:", setType);
